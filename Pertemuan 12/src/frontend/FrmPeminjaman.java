    private int parseId(String teks) {
        try {
            return Integer.parseInt(teks.trim());
        } catch (NumberFormatException e) {
            return 0;
        }
    }

    private void kosongkanForm() {
        anggotaTerpilih = null;
        bukuTerpilih = null;
        txtId.setText("");
        txtIdAnggota.setText("");
        txtIdBuku.setText("");
        txtTanggalPinjam.setText("");
        txtTanggalKembali.setText("");
        labelAnggota.setText("Anggota");
        labelBuku.setText("Buku");
    }

    private void tampilkanData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("idpeminjaman");
        model.addColumn("idanggota");
        model.addColumn("nama anggota");
        model.addColumn("idbuku");
        model.addColumn("judul buku");
        model.addColumn("tanggalpinjam");
        model.addColumn("tanggalkembali");
        for (Peminjaman p : new Peminjaman().getAll()) {
            model.addRow(new Object[]{
                p.getIdpeminjaman(),
                p.getAnggota().getIdanggota(),
                p.getAnggota().getNama(),
                p.getBuku().getIdbuku(),
                p.getBuku().getJudul(),
                p.getTanggalpinjam(),
                p.getTanggalkembali()
            });
        }
        jTable1.setModel(model);
    }

    private Anggota ambilAnggota() {
        int id = parseId(txtIdAnggota.getText());
        if (id == 0) {
            return new Anggota();
        }
        if (anggotaTerpilih != null && anggotaTerpilih.getIdanggota() == id) {
            return anggotaTerpilih;
        }
        return new Anggota().getById(id);
    }

    private Buku ambilBuku() {
        int id = parseId(txtIdBuku.getText());
        if (id == 0) {
            return new Buku();
        }
        if (bukuTerpilih != null && bukuTerpilih.getIdbuku() == id) {
            return bukuTerpilih;
        }
        return new Buku().getById(id);
    }

    private void btnCariAnggotaActionPerformed(java.awt.event.ActionEvent evt) {
        int id = parseId(txtIdAnggota.getText());
        if (id == 0) {
            anggotaTerpilih = null;
            labelAnggota.setText("ID anggota kosong");
            return;
        }
        Anggota a = new Anggota().getById(id);
        if (a.getNama() == null || a.getNama().isEmpty()) {
            anggotaTerpilih = null;
            labelAnggota.setText("Tidak ditemukan");
        } else {
            anggotaTerpilih = a;
            labelAnggota.setText(a.getNama());
        }
    }

    private void btnCariBukuActionPerformed(java.awt.event.ActionEvent evt) {
        int id = parseId(txtIdBuku.getText());
        if (id == 0) {
            bukuTerpilih = null;
            labelBuku.setText("ID buku kosong");
            return;
        }
        Buku b = new Buku().getById(id);
        if (b.getJudul() == null || b.getJudul().isEmpty()) {
            bukuTerpilih = null;
            labelBuku.setText("Tidak ditemukan");
        } else {
            bukuTerpilih = b;
            labelBuku.setText(b.getJudul());
        }
    }

    private void btnTambahBaruActionPerformed(java.awt.event.ActionEvent evt) {
        kosongkanForm();
    }

    private void tblPeminjamanMouseClicked(java.awt.event.MouseEvent evt) {
        int baris = jTable1.getSelectedRow();
        if (baris == -1) {
            return;
        }
        anggotaTerpilih = null;
        bukuTerpilih = null;
        txtId.setText(String.valueOf(jTable1.getValueAt(baris, 0)));
        txtIdAnggota.setText(String.valueOf(jTable1.getValueAt(baris, 1)));
        labelAnggota.setText(String.valueOf(jTable1.getValueAt(baris, 2)));
        txtIdBuku.setText(String.valueOf(jTable1.getValueAt(baris, 3)));
        labelBuku.setText(String.valueOf(jTable1.getValueAt(baris, 4)));
        Object pinjam = jTable1.getValueAt(baris, 5);
        txtTanggalPinjam.setText(pinjam == null ? "" : pinjam.toString());
        Object kembali = jTable1.getValueAt(baris, 6);
        txtTanggalKembali.setText(kembali == null ? "" : kembali.toString());
    }

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        Peminjaman p = new Peminjaman();
        int id = parseId(txtId.getText());
        if (id != 0) {
            p.setIdpeminjaman(id);
        }
        p.setAnggota(ambilAnggota());
        p.setBuku(ambilBuku());
        p.setTanggalpinjam(txtTanggalPinjam.getText().trim());
        p.setTanggalkembali(txtTanggalKembali.getText().trim());
        if (p.getAnggota().getIdanggota() == 0 || p.getBuku().getIdbuku() == 0) {
            JOptionPane.showMessageDialog(this, "ID Anggota dan ID Buku harus diisi.");
            return;
        }
        p.save();
        kosongkanForm();
        tampilkanData();
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        int id = parseId(txtId.getText());
        if (id == 0) {
            kosongkanForm();
            return;
        }
        Peminjaman p = new Peminjaman();
        p.setIdpeminjaman(id);
        p.delete();
        kosongkanForm();
        tampilkanData();
    }//GEN-LAST:event_btnHapusActionPerformed

